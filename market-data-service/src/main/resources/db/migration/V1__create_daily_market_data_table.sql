
CREATE TABLE daily_market_data (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   symbol VARCHAR(50) NOT NULL,
                                   trading_date DATE NOT NULL,

                                   open_price NUMERIC(19, 4) NOT NULL,
                                   high_price NUMERIC(19, 4) NOT NULL,
                                   low_price NUMERIC(19, 4) NOT NULL,
                                   close_price NUMERIC(19, 4) NOT NULL,
                                   volume BIGINT NOT NULL DEFAULT 0,

                                   created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                   CONSTRAINT uk_daily_market_data_symbol_date
                                       UNIQUE (symbol, trading_date),

                                   CONSTRAINT chk_daily_market_data_prices_positive
                                       CHECK (
                                           open_price > 0 AND
                                           high_price > 0 AND
                                           low_price > 0 AND
                                           close_price > 0
                                           ),

                                   CONSTRAINT chk_daily_market_data_price_range
                                       CHECK (
                                           high_price >= GREATEST(open_price, close_price, low_price)
                                               AND low_price <= LEAST(open_price, close_price, high_price)
                                           ),

                                   CONSTRAINT chk_daily_market_data_volume
                                       CHECK (volume >= 0)
);

CREATE INDEX idx_daily_market_data_trading_date
    ON daily_market_data (trading_date);
